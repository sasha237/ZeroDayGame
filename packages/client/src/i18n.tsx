function translate(language: Language, key: TranslationKey, values: Values = {}): string {
  const template = language === 'ru' ? ru[key] : en[key];
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translator;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => localStorage.getItem('aw.language') === 'ru' ? 'ru' : 'en');
  useEffect(() => {
    localStorage.setItem('aw.language', language);
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key: TranslationKey, values?: Values) => translate(language, key, values),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}

export function LanguageSwitcher() {
  const { language, setLanguage } = useI18n();
  return <div className="language-switcher" role="group" aria-label="Language / Язык">
    {(['en', 'ru'] as Language[]).map((value) => <button
      key={value}
      type="button"
      className={language === value ? 'active' : ''}
      aria-pressed={language === value}
      onClick={() => setLanguage(value)}
    >{value.toUpperCase()}</button>)}
  </div>;
}
